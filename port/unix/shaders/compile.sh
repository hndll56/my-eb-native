#!/bin/sh
# Regenerate blit_spv.h and ppu_spv.h from the GLSL sources. Needs glslangValidator (or glslang) on PATH.
set -e
cd "$(dirname "$0")"
G=$(command -v glslangValidator || command -v glslang)
T=$(mktemp -d)
$G -V blit.vert -o $T/blit.vert.spv
$G -V blit.frag -o $T/blit.frag.spv
$G -V ppu.comp -o $T/ppu.comp.spv
python3 - "$T" <<'PY'
import sys
T = sys.argv[1]
def arr(name, path):
    d = open(path, "rb").read()
    w = [int.from_bytes(d[i:i+4], "little") for i in range(0, len(d), 4)]
    body = ",\n".join("    " + ", ".join("0x%08x" % x for x in w[i:i+6]) for i in range(0, len(w), 6))
    return "static const uint32_t %s[] = {\n%s\n};\n" % (name, body)
hdr = "/* Generated by compile.sh. Do not edit. */\n#include <stdint.h>\n"
open("blit_spv.h", "w").write(hdr + arr("blit_vert_spv", T + "/blit.vert.spv") + arr("blit_frag_spv", T + "/blit.frag.spv"))
open("ppu_spv.h", "w").write(hdr + arr("ppu_comp_spv", T + "/ppu.comp.spv"))
PY
rm -rf "$T"
